-- Baseline: the schema Hibernate created from the entities before Flyway was introduced.
-- Runs only on an empty database. A database that already has these tables is marked as
-- version 1 (spring.flyway.baseline-on-migrate) and continues from V2.
-- Foreign key names are the ones Hibernate generated, so both kinds of database match.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP(6) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    nickname VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP(6) NOT NULL,
    name VARCHAR(255) NOT NULL,
    owner_id BIGINT NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE room_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    display_name VARCHAR(50),
    room_id BIGINT NOT NULL,
    user_id BIGINT,
    PRIMARY KEY (id),
    UNIQUE (room_id, user_id)
);

CREATE TABLE room_invite_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP(6) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    token VARCHAR(128) NOT NULL UNIQUE,
    room_id BIGINT NOT NULL UNIQUE,
    PRIMARY KEY (id)
);

CREATE TABLE room_share_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP(6) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    token VARCHAR(128) NOT NULL UNIQUE,
    room_id BIGINT NOT NULL UNIQUE,
    PRIMARY KEY (id)
);

CREATE TABLE receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    content_type VARCHAR(255),
    created_at TIMESTAMP(6) NOT NULL,
    declared_total BIGINT,
    file_size BIGINT,
    name VARCHAR(255) NOT NULL,
    original_filename VARCHAR(255),
    purchased_at DATE,
    request_fingerprint VARCHAR(64),
    request_id VARCHAR(64),
    source_type VARCHAR(30) NOT NULL CHECK (source_type IN ('IMAGE_UPLOAD', 'MANUAL')),
    stored_path VARCHAR(255),
    payer_member_id BIGINT,
    room_id BIGINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_receipt_room_request UNIQUE (room_id, request_id)
);

CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    excluded_from_settlement BOOLEAN NOT NULL,
    name VARCHAR(255) NOT NULL,
    price BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    receipt_id BIGINT NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    item_id BIGINT NOT NULL,
    room_member_id BIGINT,
    PRIMARY KEY (id),
    UNIQUE (item_id, room_member_id)
);

