-- OCR ingestion after PR 23 receipt images; no automatic settlement item insertion.
CREATE TABLE ocr_jobs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 receipt_id BIGINT NOT NULL UNIQUE REFERENCES receipts(id) ON DELETE CASCADE,
 request_id VARCHAR(64) NOT NULL, status VARCHAR(20) NOT NULL,
 provider VARCHAR(30) NOT NULL, requested_by_user_id BIGINT NOT NULL,
 created_at TIMESTAMP(6) NOT NULL, started_at TIMESTAMP(6), finished_at TIMESTAMP(6)
);
CREATE TABLE ocr_job_images (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id BIGINT NOT NULL REFERENCES ocr_jobs(id) ON DELETE CASCADE,
 image_id BIGINT NOT NULL REFERENCES receipt_images(id) ON DELETE CASCADE,
 sort_order INTEGER NOT NULL, status VARCHAR(20) NOT NULL, error_code VARCHAR(30),
 retryable BOOLEAN NOT NULL DEFAULT FALSE, attempt_count INTEGER NOT NULL DEFAULT 0,
 duration_ms BIGINT, store_name VARCHAR(255), purchased_at DATE, total_amount BIGINT,
 candidate_detail TEXT, queued_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 started_at TIMESTAMP(6), finished_at TIMESTAMP(6),
 UNIQUE(job_id,image_id)
);
CREATE TABLE ocr_drafts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id BIGINT NOT NULL UNIQUE REFERENCES ocr_jobs(id) ON DELETE CASCADE,
 receipt_id BIGINT NOT NULL REFERENCES receipts(id) ON DELETE CASCADE,
 status VARCHAR(20) NOT NULL, revision BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP(6) NOT NULL, updated_at TIMESTAMP(6) NOT NULL
);
CREATE TABLE ocr_draft_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 draft_id BIGINT NOT NULL REFERENCES ocr_drafts(id) ON DELETE CASCADE,
 image_id BIGINT NOT NULL REFERENCES receipt_images(id) ON DELETE CASCADE,
 row_index INTEGER NOT NULL, sort_order INTEGER NOT NULL,
 ocr_name VARCHAR(255), ocr_quantity INTEGER, ocr_unit_price BIGINT, ocr_line_amount BIGINT,
 ocr_flags VARCHAR(255), ocr_detail TEXT, name VARCHAR(255), price BIGINT, quantity INTEGER,
 excluded_from_settlement BOOLEAN NOT NULL DEFAULT FALSE, removed BOOLEAN NOT NULL DEFAULT FALSE,
 UNIQUE(draft_id,image_id,row_index)
);
CREATE INDEX ix_ocr_jobs_status ON ocr_jobs(status);
CREATE INDEX ix_ocr_drafts_receipt ON ocr_drafts(receipt_id);
CREATE INDEX ix_ocr_job_images_image ON ocr_job_images(image_id);
CREATE INDEX ix_ocr_draft_items_image ON ocr_draft_items(image_id);
