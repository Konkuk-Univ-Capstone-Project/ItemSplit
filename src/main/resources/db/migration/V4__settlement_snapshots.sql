-- V3 is reserved for the independent assignment migration. Integrate in V3 -> V4 order.
CREATE TABLE settlement_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    room_name VARCHAR(255) NOT NULL,
    version BIGINT NOT NULL CHECK (version > 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('CONFIRMED', 'REOPENED')),
    confirmed_by_user_id BIGINT NOT NULL,
    confirmed_at TIMESTAMP(6) NOT NULL,
    reopened_by_user_id BIGINT,
    reopened_at TIMESTAMP(6),
    request_id VARCHAR(64) NOT NULL,
    request_fingerprint VARCHAR(64) NOT NULL,
    input_fingerprint VARCHAR(64) NOT NULL,
    CONSTRAINT uk_snapshot_room_version UNIQUE(room_id, version),
    CONSTRAINT uk_snapshot_room_request UNIQUE(room_id, request_id),
    CONSTRAINT uk_snapshot_room_id UNIQUE(room_id, id),
    CONSTRAINT ck_snapshot_reopened CHECK (
        (status = 'CONFIRMED' AND reopened_at IS NULL AND reopened_by_user_id IS NULL) OR
        (status = 'REOPENED' AND reopened_at IS NOT NULL AND reopened_by_user_id IS NOT NULL))
);
CREATE TABLE room_settlement_states (
    room_id BIGINT PRIMARY KEY REFERENCES rooms(id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN', 'CONFIRMED')),
    current_snapshot_id BIGINT,
    CONSTRAINT ck_settlement_current CHECK (
        (status = 'OPEN' AND current_snapshot_id IS NULL) OR
        (status = 'CONFIRMED' AND current_snapshot_id IS NOT NULL)),
    CONSTRAINT fk_settlement_current_room FOREIGN KEY(room_id, current_snapshot_id)
        REFERENCES settlement_snapshots(room_id, id)
);
CREATE TABLE settlement_snapshot_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id BIGINT NOT NULL REFERENCES settlement_snapshots(id) ON DELETE CASCADE,
    -- Historical IDs deliberately have no reference to live room_members.
    member_id BIGINT NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    paid BIGINT NOT NULL CHECK (paid >= 0),
    burden BIGINT NOT NULL CHECK (burden >= 0),
    net BIGINT NOT NULL,
    CONSTRAINT ck_snapshot_net CHECK (net = paid - burden),
    CONSTRAINT uk_snapshot_member UNIQUE(snapshot_id, member_id)
);
CREATE TABLE settlement_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id BIGINT NOT NULL REFERENCES settlement_snapshots(id) ON DELETE CASCADE,
    from_member_id BIGINT NOT NULL,
    to_member_id BIGINT NOT NULL,
    amount BIGINT NOT NULL CHECK (amount > 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'COMPLETED')),
    updated_by_user_id BIGINT,
    updated_at TIMESTAMP(6),
    CONSTRAINT ck_transfer_distinct CHECK (from_member_id <> to_member_id),
    CONSTRAINT ck_transfer_audit CHECK ((updated_by_user_id IS NULL) = (updated_at IS NULL)),
    CONSTRAINT ck_transfer_completed CHECK (status <> 'COMPLETED' OR updated_at IS NOT NULL),
    CONSTRAINT fk_transfer_sender FOREIGN KEY(snapshot_id, from_member_id)
        REFERENCES settlement_snapshot_members(snapshot_id, member_id),
    CONSTRAINT fk_transfer_recipient FOREIGN KEY(snapshot_id, to_member_id)
        REFERENCES settlement_snapshot_members(snapshot_id, member_id)
);
CREATE INDEX ix_transfers_snapshot ON settlement_transfers(snapshot_id);
CREATE TABLE settlement_snapshot_share_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id BIGINT NOT NULL UNIQUE REFERENCES settlement_snapshots(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP(6) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_snapshot_share_expiry CHECK (expires_at > created_at)
);
