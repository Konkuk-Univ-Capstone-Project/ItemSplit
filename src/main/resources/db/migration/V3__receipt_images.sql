-- Receipt images move to their own table (up to three per receipt), and a receipt records who created it.
-- The four image columns on receipts are left in place but no longer used; a later version drops them.

ALTER TABLE receipts ADD COLUMN created_by_user_id BIGINT;

ALTER TABLE receipts
    ADD CONSTRAINT fk_receipts_created_by_user FOREIGN KEY (created_by_user_id) REFERENCES users;

CREATE TABLE receipt_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    receipt_id BIGINT NOT NULL,
    sort_order INTEGER NOT NULL,
    stored_path VARCHAR(512) NOT NULL,
    original_filename VARCHAR(255),
    content_type VARCHAR(50) NOT NULL,
    file_size BIGINT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_receipt_images_receipt_order UNIQUE (receipt_id, sort_order),
    CONSTRAINT fk_receipt_images_receipt FOREIGN KEY (receipt_id) REFERENCES receipts
);

-- Existing single images become the first image of their receipt. The stored content type came from
-- the request header, so it is kept as recorded and checked again when the image is used.
INSERT INTO receipt_images (receipt_id, sort_order, stored_path, original_filename, content_type, file_size, created_at)
SELECT r.id, 1, r.stored_path, r.original_filename,
       LEFT(COALESCE(r.content_type, 'application/octet-stream'), 50),
       COALESCE(r.file_size, 0), r.created_at
FROM receipts r
WHERE r.stored_path IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM receipt_images i WHERE i.receipt_id = r.id);
